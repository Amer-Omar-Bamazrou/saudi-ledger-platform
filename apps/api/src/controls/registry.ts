/**
 * 🔴 Phase 18 R-14 — AC-1: THE CONTROL REGISTRY (owner, 2026-11-01, memo §3; register §11.121).
 *
 * "The control registry is the single source of truth. Each entry names the control, its enforcement
 * point (file, function or trigger) and its proving test. A two-way test: every entry has its
 * enforcement point, and every enforcement point has an entry."
 *
 * One entry per Phase 18 control. An enforcement point is one of:
 *  - a database trigger, by name and table;
 *  - a named CHECK constraint, by name and table;
 *  - a code point, by repo-relative file and the symbol declared in it (`object.method` for a method).
 *
 * The two-way test is `tests/phase18-r14-ac1-control-registry.test.ts`:
 *  - FORWARD: every trigger and CHECK named here exists in the migrations and in the live database on its
 *    table; every code point's file declares its symbol; every refusal code appears in the code; every
 *    proving test exists and mentions the control's id.
 *  - REVERSE: every trigger and named CHECK the Phase 18 migrations (0121 onward) leave in place is named
 *    by an entry, so a new migration's guard has to enter the registry.
 *
 * 🔴 THE FRAME (stated beside the count): the reverse direction covers triggers and named CHECKs only.
 * Foreign keys (G04's tenant-carrying keys have their own ratchet, named by G04's entry), unique indexes
 * and code-level refusals are outside it: the code has no mechanical boundary between Phase 18's
 * refusals and earlier ones, so a code point is checked forward only.
 */

export type ControlType = "preventive" | "detective" | "approval";

export type Activation =
  | { kind: "always" }
  /** A company's typed control setting (`company_control_settings`); empty = off. */
  | { kind: "company_setting"; setting: string }
  /** A fact about the organisation the control reads at the moment it acts. */
  | { kind: "organisation_fact"; fact: string };

export type EnforcementPoint =
  | { kind: "trigger"; table: string; name: string }
  | { kind: "check"; table: string; name: string }
  | { kind: "code"; file: string; symbol: string };

export interface Control {
  /** The G row, DR, T id, or the owner's own name for the decision it builds. */
  id: string;
  title: string;
  /** The gap rows and decisions this control answers, besides its own id. */
  answers: readonly string[];
  type: ControlType;
  activation: Activation;
  /** The structured codes a refusal carries; empty where the refusal is a status and a message only. */
  refusalCodes: readonly string[];
  points: readonly EnforcementPoint[];
  /** File names under `apps/api/src/tests`; each mentions the control's id. */
  provingTests: readonly string[];
}

const trigger = (table: string, name: string): EnforcementPoint => ({ kind: "trigger", table, name });
const check = (table: string, name: string): EnforcementPoint => ({ kind: "check", table, name });
const code = (file: string, symbol: string): EnforcementPoint => ({ kind: "code", file, symbol });
const ALWAYS: Activation = { kind: "always" };

