/**
 * 🔴 19B S1 (v4 §5.3) — the contract's STRUCTURE, for the field-class seam.
 *
 * Reads `openapi.yaml` and writes `apps/api/src/lib/fieldClasses/contractShapes.generated.ts`: every operation's JSON
 * 2xx responses and JSON request body, and every component schema, as named nodes. A component's node is its name; an
 * inline object's node is its parent's name and its property (`BankingExceptions.lines.items`); an operation's inline
 * root is `<operationId>#<status>` (or `#body`). The class table (`lib/fieldClasses/classTable.ts`) classifies each
 * node's fields; the seam walks a response against these nodes to find each served key's class.
 *
 * Run by `pnpm --filter @workspace/api-spec run codegen` after orval. `--check` exits 1 when the checked-in file is
 * stale (tests/field-class-table.test.ts runs it), so the seam can never walk an older contract than the one served.
 *
 * usage: node scripts/contract-shapes.mjs [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import YAML from "yaml";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const SPEC = `${root}packages/api-spec/openapi.yaml`;
const OUT = `${root}apps/api/src/lib/fieldClasses/contractShapes.generated.ts`;
const REF = "#/components/schemas/";
const METHODS = ["get", "post", "put", "patch", "delete"];

const typesOf = (s) => (Array.isArray(s.type) ? s.type.filter((t) => t !== "null") : s.type ? [s.type] : []);
const isNullOnly = (s) => s && (s.type === "null" || (Array.isArray(s.type) && s.type.length === 1 && s.type[0] === "null"));

/** One schema as a shape; an inline object takes the node name `name`. */
function shapeOf(s, name) {
  if (!s || typeof s !== "object") return { k: "leaf" };
  if (s.$ref) {
    if (!s.$ref.startsWith(REF)) throw new Error(`unsupported $ref ${s.$ref} at ${name}`);
    return { k: "ref", n: s.$ref.slice(REF.length) };
  }
  for (const key of ["allOf", "oneOf", "anyOf"]) {
    if (!Array.isArray(s[key])) continue;
    const o = s[key].filter((p) => !isNullOnly(p)).map((p) => shapeOf(p, name));
    // Properties written beside the combinator belong to the same node.
    if (s.properties) o.push(shapeOf({ type: "object", properties: s.properties, additionalProperties: s.additionalProperties }, name));
    return o.length === 1 ? o[0] : { k: "union", o };
  }
  const t = typesOf(s);
  if (t.includes("array") || s.items) return { k: "arr", i: shapeOf(s.items ?? {}, name) };
  if (t.includes("object") || s.properties || s.additionalProperties) {
    const p = {};
    for (const [key, ps] of Object.entries(s.properties ?? {})) p[key] = shapeOf(ps, `${name}.${key}`);
    const ap = s.additionalProperties && typeof s.additionalProperties === "object" ? shapeOf(s.additionalProperties, `${name}.*`) : null;
    if (Object.keys(p).length === 0) return ap ? { k: "map", v: ap } : { k: "leaf" }; // a free-form object is one value
    return ap ? { k: "obj", n: name, p, ap } : { k: "obj", n: name, p };
  }
  return { k: "leaf" };
}

export function buildShapes(doc) {
  const components = {};
  for (const n of Object.keys(doc.components?.schemas ?? {}).sort()) components[n] = shapeOf(doc.components.schemas[n], n);
  const operations = [];
  for (const path of Object.keys(doc.paths ?? {}).sort()) {
    for (const m of METHODS) {
      const op = doc.paths[path][m];
      if (!op) continue;
      const operationId = op.operationId ?? `${m.toUpperCase()} ${path}`;
      const responses = {};
      const other = {};
      for (const status of Object.keys(op.responses ?? {}).sort()) {
        if (!/^2/.test(status)) continue;
        for (const [ct, c] of Object.entries(op.responses[status].content ?? {})) {
          if (ct === "application/json") responses[status] = shapeOf(c.schema ?? {}, `${operationId}#${status}`);
          else (other[status] ??= []).push(ct);
        }
      }
      const body = op.requestBody?.content?.["application/json"]?.schema;
      operations.push({ method: m.toUpperCase(), path, operationId, responses, other, body: body ? shapeOf(body, `${operationId}#body`) : null });
    }
  }
  return { components, operations };
}

export function render(shapes) {
  return [
    "// GENERATED by packages/api-spec/scripts/contract-shapes.mjs from packages/api-spec/openapi.yaml — do not edit.",
    "// Regenerate: pnpm --filter @workspace/api-spec run codegen. Checked fresh by tests/field-class-table.test.ts.",
    'import type { ContractShapes } from "./shapes";',
    "",
    `export const CONTRACT: ContractShapes = ${JSON.stringify(shapes)};`,
    "",
  ].join("\n");
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url).replace(/\\/g, "/") === process.argv[1].replace(/\\/g, "/");
if (isMain) {
  const text = render(buildShapes(YAML.parse(readFileSync(SPEC, "utf8"))));
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(OUT, "utf8").replace(/\r\n/g, "\n"); } catch { /* missing = stale */ }
    if (current !== text) {
      console.error(`STALE: ${OUT} does not match openapi.yaml — run \`pnpm --filter @workspace/api-spec run codegen\`.`);
      process.exit(1);
    }
    console.log("contract shapes: fresh");
  } else {
    writeFileSync(OUT, text);
    console.log(`contract shapes: wrote ${OUT}`);
  }
}
